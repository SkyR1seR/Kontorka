import { ZONE_BY_ID, STATION_BY_ID } from './map.js';

export function fmtClock(minutes) {
  const m = Math.max(0, Math.round(minutes));
  const h = Math.floor(m / 60);
  const mm = m % 60;
  return `${String(h).padStart(2, '0')}:${String(mm).padStart(2, '0')}`;
}

export function fmtSec(s) {
  s = Math.max(0, Math.ceil(s));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
}

// Шаблон: {name}, {loc}, {at}, {time}, {g:муж|жен} — выбор по роду говорящего,
// {tg:муж|жен} — по роду обсуждаемого (target).
export function fill(tpl, v) {
  return tpl
    .replace(/\{g:([^|}]*)\|([^}]*)\}/g, (_, m, f) => (v.g === 'f' ? f : m))
    .replace(/\{tg:([^|}]*)\|([^}]*)\}/g, (_, m, f) => (v.tg === 'f' ? f : m))
    .replace(/\{(\w+)\}/g, (_, k) => (v[k] !== undefined ? v[k] : `{${k}}`));
}

