// Склонение имени для простых падежей (женские на -а/-я, мужские на согласную/-ь/-й)
export function decline(name, g, cas) {
  if (!name) return name;
  const last = name.slice(-1);
  const stem = name.slice(0, -1);
  if (cas === 'nom') return name;
  if (g === 'f') {
    if (last === 'а') return { gen: stem + (/[гкхжчшщ]$/.test(stem) ? 'и' : 'ы'), dat: stem + 'е', acc: stem + 'у', ins: stem + 'ой' }[cas];
    if (last === 'я') return { gen: stem + 'и', dat: stem + 'е', acc: stem + 'ю', ins: stem + 'ей' }[cas];
    return name;
  }
  if (last === 'ь') return { gen: stem + 'я', dat: stem + 'ю', acc: stem + 'я', ins: stem + 'ем' }[cas];
  if (last === 'й') return { gen: stem + 'я', dat: stem + 'ю', acc: stem + 'я', ins: stem + 'ем' }[cas];
  if (last === 'а') return { gen: stem + 'ы', dat: stem + 'е', acc: stem + 'у', ins: stem + 'ой' }[cas];
  if (last === 'я') return { gen: stem + 'и', dat: stem + 'е', acc: stem + 'ю', ins: stem + 'ей' }[cas];
  if (/[бвгджзклмнпрстфхцчшщ]$/.test(name)) return { gen: name + 'а', dat: name + 'у', acc: name + 'а', ins: name + (/[жцчшщ]$/.test(name) ? 'ем' : 'ом') }[cas];
  return name;
}

// Беглая гласная: Колупень -> Колупня (особый случай)
const SPECIAL = {
  'Колупень': { gen: 'Колупня', dat: 'Колупню', acc: 'Колупня', ins: 'Колупнем' },
  'Шуруп': { gen: 'Шурупа', dat: 'Шурупу', acc: 'Шурупа', ins: 'Шурупом' },
};
export function declineName(name, g, cas) {
  if (SPECIAL[name] && cas !== 'nom') return SPECIAL[name][cas];
  return decline(name, g, cas);
}

export function nameVars(p) {
  return {
    name: p.name, tg: p.gender,
    gen: declineName(p.name, p.gender, 'gen'),
    dat: declineName(p.name, p.gender, 'dat'),
    acc: declineName(p.name, p.gender, 'acc'),
    ins: declineName(p.name, p.gender, 'ins'),
  };
}

